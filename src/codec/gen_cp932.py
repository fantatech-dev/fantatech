#!/usr/bin/env python3
"""
Generates src/codec/cp932_table.c: CP932 (Windows Shift-JIS) -> Unicode tables built
from Python's own cp932 codec. Unmapped codes are 0.

    py src/codec/gen_cp932.py > src/codec/cp932_table.c
"""

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = range(0x40, 0xFD)


def decode(b):
    try:
        s = b.decode("cp932")
    except UnicodeDecodeError:
        return 0
    return ord(s) if len(s) == 1 else 0


def main():
    out = []
    out.append("/* Generated by src/codec/gen_cp932.py from Python's cp932 codec. Do not edit. */")
    out.append('#include "codec/cp932.h"')
    out.append("")
    out.append("const uint16_t ft_cp932_single[256] = {")
    row = [decode(bytes([b])) if b not in LEADS else 0 for b in range(256)]
    for i in range(0, 256, 16):
        out.append("    " + ", ".join(f"0x{v:04x}" for v in row[i:i + 16]) + ",")
    out.append("};")
    out.append("")
    out.append(f"const uint16_t ft_cp932_double[{len(LEADS)}][{len(TRAILS)}] = {{")
    for lead in LEADS:
        vals = [decode(bytes([lead, t])) for t in TRAILS]
        out.append(f"    {{ /* 0x{lead:02x} */")
        for i in range(0, len(vals), 16):
            out.append("        " + ", ".join(f"0x{v:04x}" for v in vals[i:i + 16]) + ",")
        out.append("    },")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
